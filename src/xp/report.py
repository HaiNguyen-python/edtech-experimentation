SURFACE, INK, INK_2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
BLUE, GREY = "#2a78d6", "#b7b7b2"
DATA_LABEL = "Synthetic data"


def _pct(x: float, digits: int = 1) -> str:
    return f"{x:+.{digits}%}"


def _p(p: float | None) -> str:
    if p is None:
        return "-"
    return f"{p:.1e}" if p < 0.001 else f"{p:.3f}"


def _ci(est: Estimate) -> str:
    return f"{_pct(est.rel)} ({_pct(est.rel_ci_low)} to {_pct(est.rel_ci_high)})"


def _status(flag: bool) -> str:
    return "FAIL" if flag else "pass"


# ---------------------------------------------------------------- per-experiment report


def experiment_markdown(r: ExperimentResult, chart_name: str) -> str:
    exp = r.experiment
    plain = r.primary_plain
    lines = [
        f"# {exp.title} (`{exp.name}`)",
        "",
        f"Data: **{DATA_LABEL}** (seeded generator, story planted on purpose). "
        f"Generated by `xp analyze {exp.name}`.",
        "",
        f"## Decision: **{r.decision.upper()}**",
        "",
        *[f"- {reason}" for reason in r.reasons],
        "",
        f"Hypothesis: {exp.hypothesis}",
        "",
        f"Design: layer `{exp.layer}`, buckets {exp.buckets[0]}-{exp.buckets[1] - 1} of 1000, "
        f"split {' / '.join(f'{k} {v:.0%}' for k, v in exp.variants.items())}, users enter over "
        f"{exp.ramp_days} days and each is followed for {exp.window_days} days after first "
        f"exposure. {r.n_users:,} exposed users. Analysis: {exp.analysis}.",
        "",
        "## Checks (before looking at results)",
        "",
        "| Check | Result | Status |",
        "| --- | --- | --- |",
    ]
    srm, bal, pw = r.srm, r.balance, r.power
    observed = ", ".join(f"{k} {v:,}" for k, v in srm.observed.items())
    lines.append(
        f"| Sample ratio (SRM) | {observed}; chi-square {srm.chi2:.2f}, p = {_p(srm.p_value)} "
        f"(flag if p < 0.001) | {_status(srm.flagged)} |"
    )
    pre = "no pre-period (new users)" if bal.pre_period_p is None else f"p = {_p(bal.pre_period_p)}"
    lines.append(
        f"| Pre-period balance | pre-period lessons: {pre}; platform mix: "
        f"p = {_p(bal.platform_mix_p)} | {_status(bal.flagged)} |"
    )
    cuped_mde = "" if pw.mde_rel_cuped is None else f" ({pw.mde_rel_cuped:.1%} with CUPED)"
    lines.append(
        f"| Power | MDE {pw.mde_rel:.1%}{cuped_mde} at 80% power vs planned "
        f"{pw.planned_mde:.0%}; planned effect needs {pw.required_per_arm:,} users per arm "
        f"without CUPED | {'pass' if pw.powered else 'underpowered'} |"
    )
    lines += [
        "",
        "Users per platform (SRM by platform):",
        "",
        f"| Platform | {exp.control} | {exp.treatment} | Share in treatment | p |",
        "| --- | --- | --- | --- | --- |",
    ]
    for prow in srm.by_platform.to_dict("records"):
        lines.append(
            f"| {prow['platform']} | {prow[exp.control]:,} | {prow[exp.treatment]:,} | "
            f"{prow['share_treatment']:.1%} | {_p(prow['p_value'])} |"
        )
    lines += [
        "",
        "## Metrics",
        "",
        "| Metric | Role | Method | Control | Treatment | Relative change (95% CI) | p | "
        "Holm p | Status |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        f"| {exp.primary} | primary (raw) | Welch t-test | {plain.control:.4f} | "
        f"{plain.treatment:.4f} | {_ci(plain)} | {_p(plain.p_value)} | - | "
        f"{'see CUPED' if r.primary_cuped else r.rows[0].status} |",
    ]
    for row in r.rows:
        if row.role == "primary" and r.primary_cuped is None:
            continue
        est = row.estimate
        lines.append(
            f"| {row.metric.name} | {row.role} | {row.method} | {est.control:.4f} | "
            f"{est.treatment:.4f} | {_ci(est)} | {_p(est.p_value)} | {_p(row.p_adjusted)} | "
            f"{row.status} |"
        )
    if r.primary_cuped is not None:
        c = r.primary_cuped
        width_cut = 1 - (c.estimate.ci_high - c.estimate.ci_low) / (plain.ci_high - plain.ci_low)
        lines += [
            "",
            f"CUPED: theta = {c.theta:.3f} on pre-period lessons per week; variance reduced by "
            f"{c.variance_reduction:.1%}, CI {width_cut:.1%} narrower than the raw t-test.",
        ]
    lines += [
        "",
        "Guardrails fail when they are significantly worse AND worse than the catalog "
        "threshold (10% relative). Secondary metrics use Holm-adjusted p-values and do not "
        "decide on their own.",
    ]
    if r.monitoring is not None:
        mon = r.monitoring
        lines += [
            "",
            "## Daily monitoring",
            "",
            "What a dashboard showed each day (users whose 7-day window had ended). The naive "
            "t-test p-value is only valid at one pre-planned look; the always-valid mSPRT "
            "p-value and confidence sequence stay valid at every look.",
            "",
            "| Day | Users | Difference | Naive 95% CI | Naive p | Confidence sequence | "
            "Always-valid p |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
        win_day = r.naive_win_day()
        days = sorted(
            {*mon["day"].iloc[::7].tolist(), int(mon["day"].iloc[-1])}
            | ({win_day} if win_day else set())
        )
        for look in mon[mon["day"].isin(days)].to_dict("records"):
            lines.append(
                f"| {look['day']} | {int(look['n']):,} | {look['diff']:+.3f} | "
                f"{look['naive_low']:+.3f} to {look['naive_high']:+.3f} | {_p(look['naive_p'])} | "
                f"{look['cs_low']:+.3f} to {look['cs_high']:+.3f} | {_p(look['always_valid_p'])} |"
            )
    lines += ["", f"![{exp.name}]({chart_name})", ""]
    return "\n".join(lines)


def _style(ax) -> None:
    ax.set_facecolor(SURFACE)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    ax.spines["left"].set_color(GRID)
    ax.spines["bottom"].set_color(GRID)
    ax.grid(color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    ax.tick_params(colors=INK_2, labelsize=9, length=0)


def _header(fig, title: str, subtitle: str) -> None:
    fig.text(0.012, 0.965, title, fontsize=12.5, fontweight="bold", color=INK, va="top")
    fig.text(0.012, 0.895, subtitle, fontsize=9.5, color=INK_2, va="top")


def _forest(ax, labels: list[str], ests: list[Estimate], highlight: int) -> None:
    import matplotlib.pyplot as plt

    for y, est in enumerate(ests):
        color = BLUE if y == highlight else GREY
        ax.plot(
            [est.rel_ci_low, est.rel_ci_high],
            [y, y],
            color=color,
            linewidth=3,
            solid_capstyle="round",
        )
        ax.plot(est.rel, y, "o", color=color, markersize=8)
        ax.text(
            est.rel_ci_high, y + 0.22, f" {_pct(est.rel)}", fontsize=8.5, color=INK, va="bottom"
        )
    ax.axvline(0, color=INK_2, linewidth=1)
    ax.set_yticks(range(len(labels)))
    ax.set_yticklabels(labels)
    ax.set_ylim(-0.6, len(labels) - 0.2)
    ax.invert_yaxis()
    _style(ax)
    ax.grid(axis="y", visible=False)
    ax.xaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: f"{v:+.0%}"))
    ax.set_xlabel("Relative change, treatment vs control (95% CI)", fontsize=9, color=INK_2)


def plot_experiment(r: ExperimentResult, path: Path) -> None:
    import matplotlib.pyplot as plt

    exp = r.experiment
    path.parent.mkdir(parents=True, exist_ok=True)
    if r.monitoring is not None:
        mon = r.monitoring
        fig, ax = plt.subplots(figsize=(10, 4.2), dpi=150)
        fig.set_facecolor(SURFACE)
        ax.fill_between(
            mon["day"], mon["cs_low"], mon["cs_high"], color=BLUE, alpha=0.18, linewidth=0
        )
        ax.fill_between(
            mon["day"], mon["naive_low"], mon["naive_high"], color=GREY, alpha=0.6, linewidth=0
        )
        ax.plot(mon["day"], mon["diff"], color=INK, linewidth=1.5, label="difference")
        ax.axhline(0, color=INK_2, linewidth=1)
        # Legend handles for the two bands (direct labels collide where the bands meet).
        ax.fill_between([], [], [], color=BLUE, alpha=0.18, label="mSPRT confidence sequence")
        ax.fill_between([], [], [], color=GREY, alpha=0.6, label="daily t-test 95% CI")
        legend = ax.legend(loc="upper right", frameon=False, fontsize=8.5)
        for text in legend.get_texts():
            text.set_color(INK_2)
        win = r.naive_win_day()
        if win is not None:
            hit = mon[mon["day"] == win].to_dict("records")[0]
            ax.plot(win, hit["diff"], "o", color=INK, markersize=6)
            ax.annotate(
                f"day {win}: daily t-test p = {hit['naive_p']:.3f}, a false 'win'",
                (win, hit["diff"]),
                xytext=(win - 12, 0.75 * float(np.nanmax(mon["cs_high"].iloc[3:]))),
                fontsize=8.5,
                color=INK,
                arrowprops={"arrowstyle": "-", "color": INK_2},
            )
        _style(ax)
        span = 1.1 * float(np.nanmax(np.abs(mon[["cs_low", "cs_high"]].iloc[3:].to_numpy())))
        ax.set_ylim(-span, span)  # the first looks have huge bands; clip them
        ax.set_xlim(mon["day"].min() - 0.5, mon["day"].max() + 0.5)
        ax.set_xlabel("Day of the experiment (look)", fontsize=9, color=INK_2)
        ax.set_ylabel("Lessons per week, difference", fontsize=9, color=INK_2)
        title = (
            f"Daily t-test crossed zero on day {win}; the confidence sequence never did"
            if win
            else "Neither the daily t-test nor the confidence sequence excluded zero"
        )
        subtitle = f"{exp.title}: true effect is zero. {r.n_users:,} users. {DATA_LABEL}."
    else:
        labels, ests = [f"{exp.primary} (raw)"], [r.primary_plain]
        highlight = 0
        if r.primary_cuped is not None:
            labels.append(f"{exp.primary} (CUPED)")
            ests.append(r.primary_cuped.estimate)
            highlight = 1
        for row in r.rows[1:]:
            if row.status == "fail":
                highlight = len(labels)  # a failed guardrail is what decided
            labels.append(f"{row.metric.name} ({row.role})")
            ests.append(row.estimate)
        fig, ax = plt.subplots(figsize=(10, 0.55 * len(labels) + 1.9), dpi=150)
        fig.set_facecolor(SURFACE)
        _forest(ax, labels, ests, highlight)
        title = f"{exp.title}: decision {r.decision.upper()}"
        if r.decision == "investigate":
            subtitle = (
                "For reference only: a pre-check failed, so these estimates are not "
                f"trustworthy. {r.n_users:,} exposed users. {DATA_LABEL}."
            )
        else:
            subtitle = f"Blue: the metric that decided. {r.n_users:,} exposed users. {DATA_LABEL}."
    _header(fig, title, subtitle)
    fig.tight_layout(rect=(0, 0, 1, 0.84))
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)


def write_experiment(r: ExperimentResult, out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    chart = f"{r.experiment.name}.png"
    plot_experiment(r, out_dir / chart)
    md = out_dir / f"{r.experiment.name}.md"
    md.write_text(experiment_markdown(r, chart))
    return md


# ---------------------------------------------------------------- the whole study


@dataclass(frozen=True)
class StudyConfig:
    seed: int = synth.DEFAULT_SEED
    scale: float = 1.0
    aa_reps: int = 4000
    lift_reps: int = 2000
    n_per_arm: int = 2000
    peeking_reps: int = 4000
    power_reps: int = 400
    power_sizes: tuple[int, ...] = (2000, 4000, 8000, 12000, 16000)


@dataclass
class Study:
    config: StudyConfig
    tables: dict[str, int]
    duplicate_exposures: int
    results: list[ExperimentResult]
    aa: FixedHorizon
    lift: FixedHorizon
    peek: Peeking
    power: list[PowerPoint]


def _count(con: duckdb.DuckDBPyConnection, sql: str) -> int:
    row = con.execute(sql).fetchone()
    return int(row[0]) if row else 0


def run_study(cfg: StudyConfig, data_dir: Path | None = None) -> Study:
    if data_dir is not None and (data_dir / "events.parquet").exists():
        con = pipeline.connect(data_dir)
    else:
        tables = synth.generate(cfg.seed, cfg.scale)
        if data_dir is not None:
            synth.write(tables, data_dir)
        con = pipeline.connect(tables)
    sizes = {t: _count(con, f"SELECT count(*) FROM {t}") for t in pipeline.SCHEMA}
    dupes = _count(con, "SELECT count(*) - count(DISTINCT (experiment, user_id)) FROM exposures")
    metrics = load_metrics()
    results = [analyze(con, exp, metrics) for exp in load_experiments().values()]
    return Study(
        config=cfg,
        tables=sizes,
        duplicate_exposures=dupes,
        results=results,
        aa=fixed_horizon(cfg.aa_reps, cfg.n_per_arm, 0.0, seed=10),
        lift=fixed_horizon(cfg.lift_reps, cfg.n_per_arm, 0.03, seed=11),
        peek=peeking(cfg.peeking_reps, seed=12),
        power=power_curve(list(cfg.power_sizes), cfg.power_reps, 0.03, seed=13),
    )


def _rate(r: Rate) -> str:
    low, high = r.ci
    return f"{r.value:.1%} ({low:.1%} to {high:.1%})"


PLANTED_TEXT = {
    "practice_reminder": "+3% lessons, guardrails flat",
    "aa_check": "no difference (A/A)",
    "streak_badge": "Android bug: 15% of treatment shown and logged as control",
    "home_redesign": "no effect; watched daily",
    "new_onboarding": "+5% lessons, crash rate x1.5",
}


def results_markdown(study: Study) -> str:
    cfg, aa, lift, peek = study.config, study.aa, study.lift, study.peek
    t = study.tables
    lines = [
        "# Results",
        "",
        f"Data: **{DATA_LABEL}** from `xp.synth` (seed {cfg.seed}). Every effect below was "
        "planted on purpose so that the platform can be checked against a known truth. All "
        "numbers come from `xp report`; rerun it to reproduce them.",
        "",
        f"Logs: {t['users']:,} users, {t['exposures']:,} exposure rows "
        f"({study.duplicate_exposures:,} repeat visits removed by the SQL), "
        f"{t['events']:,} events.",
        "",
        "## 1. The five experiments",
        "",
        "| Experiment | Planted truth | Users | SRM p | Primary effect (95% CI) | Method | "
        "Decision |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in study.results:
        name = r.experiment.name
        method = "CUPED" if r.primary_cuped else "Welch t-test"
        if r.experiment.analysis == "sequential" and r.monitoring is not None:
            method += f" + mSPRT (always-valid p {r.monitoring['always_valid_p'].iloc[-1]:.2f})"
        lines.append(
            f"| [{name}](experiments/{name}.md) | {PLANTED_TEXT.get(name, '')} | "
            f"{r.n_users:,} | {_p(r.srm.p_value)} | {_ci(r.primary)} | {method} | "
            f"**{r.decision}** |"
        )
    lines += [""]
    for r in study.results:
        lines.append(f"- **{r.experiment.name}**: " + " ".join(r.reasons))
    reminder = next(r for r in study.results if r.experiment.name == "practice_reminder")
    if reminder.primary_cuped is not None:
        c, plain = reminder.primary_cuped, reminder.primary_plain
        width_cut = 1 - (c.estimate.ci_high - c.estimate.ci_low) / (plain.ci_high - plain.ci_low)
        lines += [
            "",
            f"Reminder, raw vs CUPED: raw t-test {_ci(plain)}, p = {_p(plain.p_value)}; CUPED "
            f"{_ci(c.estimate)}, p = {_p(c.estimate.p_value)}. CUPED cut the variance by "
            f"{c.variance_reduction:.1%} and the CI width by {width_cut:.1%}. Both intervals "
            "contain the planted +3%.",
        ]
    lines += [
        "",
        "## 2. Simulations: do the statistics keep their promises?",
        "",
        f"Simulated experiments drawn from the same user model as the logs, "
        f"{cfg.n_per_arm:,} users per arm, 2-week window. Rates have Wilson 95% intervals.",
        "",
        "### False positives with no effect (A/A)",
        "",
        "| Method | False-positive rate at alpha = 5% | Mean CI width (lessons/week) |",
        "| --- | --- | --- |",
        f"| Welch t-test | {_rate(aa.plain_reject)} | {aa.plain_ci_width:.3f} |",
        f"| CUPED | {_rate(aa.cuped_reject)} | {aa.cuped_ci_width:.3f} |",
        "",
        f"{aa.reps:,} simulated A/A tests. CUPED reduced the variance by "
        f"{aa.variance_reduction:.1%} on average and the CI width by {aa.width_reduction:.1%}, "
        "with the same false-positive rate.",
        "",
        "### CUPED is unbiased (true lift +3%)",
        "",
        "| Method | Mean estimated difference | True difference | Power |",
        "| --- | --- | --- | --- |",
        f"| Welch t-test | {lift.plain_mean_diff:.4f} (MC s.e. {lift.mc_se(lift.plain_sd):.4f}) "
        f"| {lift.true_diff:.4f} | {_rate(lift.plain_reject)} |",
        f"| CUPED | {lift.cuped_mean_diff:.4f} (MC s.e. {lift.mc_se(lift.cuped_sd):.4f}) "
        f"| {lift.true_diff:.4f} | {_rate(lift.cuped_reject)} |",
        "",
        f"{lift.reps:,} simulated experiments. The spread of the estimate across experiments "
        f"is {lift.plain_sd:.4f} raw vs {lift.cuped_sd:.4f} with CUPED.",
        "",
        "### Peeking every day",
        "",
        f"{peek.reps:,} simulated A/A tests, {peek.users_per_day} new users per arm per day, "
        f"each followed 1 week, looked at every day for {peek.days} days (like home_redesign). "
        "A test counts as a false positive if it rejects (either direction) at any look "
        "so far.",
        "",
        "| Looks so far | Daily t-test: false-positive rate | mSPRT: false-positive rate |",
        "| --- | --- | --- |",
    ]
    for k in (1, 7, 14, 21, peek.days):
        lines.append(
            f"| {k} | {_rate(peek.ttest_by_look[k - 1])} | {_rate(peek.msprt_by_look[k - 1])} |"
        )
    lines += [
        "",
        f"A single t-test at the last day only: {_rate(peek.ttest_final_only)}.",
        "",
        "![False positives under daily peeking](img/peeking_false_positives.png)",
        "",
        "### Power vs sample size (true lift +3%)",
        "",
        "| Users per arm | Welch t-test | CUPED | Analytic (t-test) |",
        "| --- | --- | --- | --- |",
    ]
    for pt in study.power:
        lines.append(
            f"| {pt.n_per_arm:,} | {_rate(pt.plain)} | {_rate(pt.cuped)} | {pt.analytic:.1%} |"
        )
    lines += [
        "",
        f"{cfg.power_reps} simulated experiments per size. The analytic column uses the normal "
        "approximation with the simulated variance; the simulated t-test power should match it.",
        "",
        "![Reminder effect, raw vs CUPED](img/reminder_effect.png)",
        "",
    ]
    return "\n".join(lines)


def plot_peeking(peek: Peeking, path: Path) -> None:
    import matplotlib.pyplot as plt

    days = np.arange(1, peek.days + 1)
    fig, ax = plt.subplots(figsize=(10, 4.4), dpi=150)
    fig.set_facecolor(SURFACE)
    for rates, color, label in (
        (peek.ttest_by_look, GREY, "daily t-test"),
        (peek.msprt_by_look, BLUE, "mSPRT"),
    ):
        value = np.array([r.value for r in rates])
        ci = np.array([r.ci for r in rates])
        ax.fill_between(days, ci[:, 0], ci[:, 1], color=color, alpha=0.25, linewidth=0)
        ax.plot(days, value, color=color, linewidth=2.5)
        ax.text(
            days[-1] + 0.4,
            max(value[-1], 0.025),
            f"{label}\n{value[-1]:.1%}",
            color=color,
            fontsize=9,
            va="center",
            fontweight="bold",
        )
    ax.axhline(0.05, color=INK_2, linestyle=":", linewidth=1)
    ax.text(peek.days, 0.057, "5% promised", fontsize=8.5, color=INK_2, ha="right")
    _style(ax)
    ax.set_xlim(0.5, peek.days + 4)
    ax.set_ylim(0, max(0.35, peek.ttest_any.value + 0.05))
    ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: f"{v:.0%}"))
    ax.set_xlabel("Number of daily looks", fontsize=9, color=INK_2)
    ax.set_ylabel("A/A tests with p < 0.05 at some look", fontsize=9, color=INK_2)
    _header(
        fig,
        f"Peeking daily turns a 5% false-positive rate into {peek.ttest_any.value:.0%}; "
        f"mSPRT stays at {peek.msprt_any.value:.1%}",
        f"{peek.reps:,} simulated A/A tests, {peek.users_per_day} users per arm per day, "
        f"{peek.days} looks. Bands: Wilson 95% intervals. {DATA_LABEL}.",
    )
    fig.tight_layout(rect=(0, 0, 1, 0.85))
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)


def plot_reminder(study: Study, path: Path) -> None:
    import matplotlib.pyplot as plt

    r = next(x for x in study.results if x.experiment.name == "practice_reminder")
    ests = [r.primary_plain] + ([r.primary_cuped.estimate] if r.primary_cuped else [])
    labels = ["Welch t-test (raw)", "CUPED"][: len(ests)]
    fig, ax = plt.subplots(figsize=(10, 3.4), dpi=150)
    fig.set_facecolor(SURFACE)
    _forest(ax, labels, ests, highlight=len(ests) - 1)
    ax.axvline(0.03, color=BLUE, linestyle=":", linewidth=1)
    ax.text(0.03, -0.55, " planted +3%", color=BLUE, fontsize=8.5, va="bottom")
    ax.set_xlim(-0.01, max(e.rel_ci_high for e in ests) + 0.02)
    width_cut = 1 - (ests[-1].ci_high - ests[-1].ci_low) / (ests[0].ci_high - ests[0].ci_low)
    _header(
        fig,
        f"The reminder lifts weekly lessons; CUPED makes the CI {width_cut:.0%} narrower",
        f"Lessons completed per week, {r.n_users:,} exposed users. In simulation CUPED cut CI "
        f"width by {study.aa.width_reduction:.0%} with a 5% false-positive rate. {DATA_LABEL}.",
    )
    fig.tight_layout(rect=(0, 0, 1, 0.8))
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)


def write(out_dir: Path, cfg: StudyConfig | None = None, data_dir: Path | None = None) -> Study:
    study = run_study(cfg or StudyConfig(), data_dir)
    for r in study.results:
        write_experiment(r, out_dir / "experiments")
    (out_dir / "results.md").write_text(results_markdown(study))
    plot_peeking(study.peek, out_dir / "img" / "peeking_false_positives.png")
    plot_reminder(study, out_dir / "img" / "reminder_effect.png")
    return study


def summary_frame(study: Study) -> pd.DataFrame:
    """One line per experiment, printed by the CLI."""
    return pd.DataFrame(
        [
            {
                "experiment": r.experiment.name,
                "users": r.n_users,
                "primary_rel": round(r.primary.rel, 4),
                "decision": r.decision,
            }
            for r in study.results
        ]
    )
